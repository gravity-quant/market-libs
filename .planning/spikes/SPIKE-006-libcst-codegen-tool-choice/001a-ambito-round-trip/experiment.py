"""SPIKE-006 001a driver (IMPURE, stateful) — parse ámbito ``aio.py`` → pure transformer
passes → scope-aware module.body edits → ``@generated`` marker → emit ``client_generated.py``,
then run the fast item-1 (diff) / item-2 (B8) / item-9 (purity) smokes.

Integrity guardrails (D-02, D-03, D-04):
  - ``aio.py`` is the SOLE source and is NEVER edited (parsed from a read of the production
    file; nothing is written back to ``packages/``).
  - ``client.py`` is the byte-identity ORACLE and is NEVER read here as a content donor.
  - The two content-absent-from-source regions (``_validate_max_retries`` def; ``load_dotenv``
    import+call) cannot be synthesized by any pure transform of ``aio.py``. The driver records
    the residual honestly — it does NOT smuggle a donor read to manufacture a GO.

All cross-module / scope-aware orchestration (computing locally-defined names, removing the
module-level ``close`` delegator, marker insertion) lives HERE, not in a ``CSTTransformer`` —
that is what keeps the transformer subclasses pure (item 9, RESEARCH Pattern 2 / Q2).

Run from repo root (ephemeral libcst — D-05, never added to dev deps):

    uv run --with 'libcst>=1.8.0,<2' python \
      .planning/spikes/SPIKE-006-libcst-codegen-tool-choice/001a-ambito-round-trip/experiment.py
"""

from __future__ import annotations

import copy
import subprocess
import sys
from pathlib import Path

import libcst as cst

sys.path.insert(0, str(Path(__file__).resolve().parent / "transformers"))

from async_to_sync import AsyncToSync  # noqa: E402
from docstring_localizer import DocstringLocalizer  # noqa: E402
from import_direction_normalizer import ImportDirectionNormalizer  # noqa: E402
from import_normalizer import ImportNormalizer  # noqa: E402
from suppressors import Suppressors  # noqa: E402

# --- paths ----------------------------------------------------------------

REPO_ROOT = Path(__file__).resolve().parents[4]
AMBITO_SRC = REPO_ROOT / "packages/ambito-financiero-client/src/ambito_financiero_client"
AIO = AMBITO_SRC / "aio.py"
CLIENT = AMBITO_SRC / "client.py"  # ORACLE ONLY — diffed, never parsed as a donor
SPIKE_DIR = Path(__file__).resolve().parent
OUTPUT = SPIKE_DIR / "output" / "client_generated.py"
DIFF = SPIKE_DIR / "diff_vs_current_client.txt"

MARKER: list[cst.EmptyLine] = [
    cst.EmptyLine(comment=cst.Comment("# @generated by libcst from aio.py — DO NOT EDIT BY HAND.")),
    cst.EmptyLine(comment=cst.Comment("# To modify, edit aio.py and run `make codegen` (Phase 19).")),
    cst.EmptyLine(),
]

# --- preflight ------------------------------------------------------------

for p in (AIO, CLIENT):
    if not p.exists():
        sys.stderr.write(f"FATAL: missing source {p}\n")
        raise SystemExit(2)

AIO_SRC = AIO.read_text()

# --- step 1: lossless round-trip smoke (validates the TOOL; Pitfall 3) ----
# Distinct from the item-1 target diff: this only proves parse→emit reproduces the INPUT.

module = cst.parse_module(AIO_SRC)
lossless = module.code == AIO_SRC
print(f"[item-tool] libcst lossless round-trip on aio.py: {'PASS' if lossless else 'FAIL'}")
if not lossless:
    raise SystemExit(3)

# --- step 2: compute driver orchestration state (scope-aware, IMPURE) -----
# Names DEFINED at module scope in the source. `_validate_max_retries` is NOT among them —
# aio.py only IMPORTS it (Q1) — so ImportDirectionNormalizer will RETAIN the self-import.

module_level_defs = frozenset(
    s.name.value for s in module.body if isinstance(s, cst.FunctionDef)
)
print(f"[driver] module-level defs in aio.py: {sorted(module_level_defs)}")
validate_locally_defined = "_validate_max_retries" in module_level_defs
print(
    "[Q1] `_validate_max_retries` locally defined in aio.py source: "
    f"{validate_locally_defined}  (False → content-absent → self-import retained, honest residual)"
)
# Precise bootstrap detection: the import + call, NOT the docstring mention
# ("D-19: NO llama load_dotenv()") which is prose, not executable content.
has_dotenv_import = "from dotenv import load_dotenv" in AIO_SRC
print(
    f"[Q1] dotenv bootstrap (`from dotenv import load_dotenv`) present in aio.py source: "
    f"{has_dotenv_import}  (False → cannot be synthesized by a pure transform → residual)"
)

# --- step 3: apply the pure transformer passes ----------------------------
# Order: async→sync (renames first) → import-order → docstring labels → suppressions →
# import-direction (uses driver-computed locally-defined set).

passes: list[cst.CSTTransformer] = [
    AsyncToSync(),
    ImportNormalizer(),
    DocstringLocalizer(),
    Suppressors(),
    ImportDirectionNormalizer(module_level_defs),
]

# item-9 purity assertion (driver-level): visiting MUST NOT mutate a transformer instance.
purity_ok = True
for t in passes:
    probe = cst.parse_module(AIO_SRC)
    before = copy.deepcopy(vars(t))
    probe.visit(t)
    after = vars(t)
    same = set(before) == set(after) and all(before[k] == after[k] for k in before)
    purity_ok = purity_ok and same
    print(f"[item-9] {type(t).__name__} pure (vars unchanged across visit): {'PASS' if same else 'FAIL'}")

transformed = module
for t in passes:
    transformed = transformed.visit(t)

# --- step 4: driver scope-aware edit — drop module-level `close` delegator -
# aio.py:266 `async def aclose()` became `def close()` after AsyncToSync. The hand-written
# client.py has NO module-level sync delegator. Distinguishing the module-level def from the
# class method needs module SCOPE → orchestration lives in the driver, not a transformer.

new_body = [
    s
    for s in transformed.body
    if not (isinstance(s, cst.FunctionDef) and s.name.value == "close")
]
dropped = len(transformed.body) - len(new_body)
print(f"[driver] module-level `close` delegator(s) dropped: {dropped}")
transformed = transformed.with_changes(body=new_body)

# --- step 5: prepend @generated marker via Module.header (never str.replace) --

transformed = transformed.with_changes(header=[*MARKER, *transformed.header])

# --- step 6: emit ---------------------------------------------------------

OUTPUT.parent.mkdir(parents=True, exist_ok=True)
GENERATED = transformed.code
OUTPUT.write_text(GENERATED)
print(f"[emit] wrote {OUTPUT.relative_to(REPO_ROOT)} ({len(GENERATED.splitlines())} lines)")

# --- step 7: B8 preservation (item-2 static check) ------------------------
# The alias must be emitted VERBATIM — no thunk wrapper (Pitfall 4). Full `is`-triple
# identity is asserted at runtime in Task 2; here we assert the literal survives.

b8_literal = "_raise_for_response = _core.raise_for_response" in GENERATED
print(f"[item-2/static] `_raise_for_response = _core.raise_for_response` verbatim: {'PASS' if b8_literal else 'FAIL'}")

# --- step 8: item-1 diff vs CURRENT client.py (regenerated; Pitfall 1) -----
# Diff ORACLE vs generated. client.py is READ ONLY for `diff` — never parsed as a donor.

proc = subprocess.run(
    ["diff", "-u", str(CLIENT), str(OUTPUT)],
    capture_output=True,
    text=True,
    cwd=REPO_ROOT,
)
DIFF.write_text(proc.stdout)
hunks = proc.stdout.count("\n@@ ")
diff_lines = len(proc.stdout.splitlines())
item1_pass = proc.returncode == 0
print(
    f"[item-1] diff vs current client.py: {'PASS (byte-identical)' if item1_pass else 'FAIL'}  "
    f"(exit={proc.returncode}, hunks={hunks}, diff_lines={diff_lines}) → {DIFF.relative_to(REPO_ROOT)}"
)

# Self-import residual detection (the decisive Q1 evidence).
self_import_retained = (
    "from ambito_financiero_client.client import _validate_max_retries" in GENERATED
)
print(
    f"[Q1] generated output retains the `_validate_max_retries` self-import: {self_import_retained}  "
    "(True → reproduces SPIKE-005 item-6 circular ImportError → honest FAIL, valid per D-04/D-08)"
)

# --- step 9: aio.py source untouched (T-18-02) ----------------------------

aio_untouched = AIO.read_text() == AIO_SRC
print(f"[T-18-02] aio.py source untouched by the run: {'PASS' if aio_untouched else 'FAIL'}")

print(
    "\n=== 001a driver summary ===\n"
    f"  tool round-trip: {'PASS' if lossless else 'FAIL'}\n"
    f"  item-9 purity:   {'PASS' if purity_ok else 'FAIL'}\n"
    f"  item-2 B8 lit:   {'PASS' if b8_literal else 'FAIL'}\n"
    f"  item-1 diff:     {'PASS' if item1_pass else 'FAIL'} (hunks={hunks})\n"
    f"  Q1 self-import:  {'RETAINED (residual)' if self_import_retained else 'absent'}\n"
    f"  aio.py untouched:{'PASS' if aio_untouched else 'FAIL'}\n"
)

# The driver never fails the run on an item-1 FAIL: an honest FAIL is the deliverable (D-04).
raise SystemExit(0 if (lossless and purity_ok and aio_untouched) else 1)
